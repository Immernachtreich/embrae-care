#!/usr/bin/env python3
"""Write each page's complete CSS in its original order, so templates match their source page exactly:
embrae-pdp-<step>.css for product pages, embrae-sections.css for the home page. theme.liquid loads one of these
INSTEAD of embrae-base.css (splitting base out reorders the cascade, e.g. .step-grid row-gap on mobile)."""
import json, re
import build_css as B  # re-runs the base split (deterministic) and gives us its helpers

# asset_ref misses quoted urls; asset-04.png ships as embrae-logo.png
fix = lambda css: css.replace('"../assets/', '"').replace("asset-04.png", "embrae-logo.png")
steps = {}
for name, rs in B.R.items():
    page = (B.root / "source/pages" / name).read_text()
    m = re.search(r'class="pd-pan pan1[^"]*".*?<svg class="prod"[^>]*><use href="#p-(\w+)"', page, flags=re.S)
    step = "bundle" if name == "daily-urban-defense-routine.html" else (m.group(1) if m else None)
    if not step: continue
    rules = B.dedupe_keep_last([r for r in rs if not B.PREVIEW_ONLY.match(r)])
    out = B.theme_assets / f"embrae-pdp-{step}.css"
    out.write_text(f"/* {name}: complete page CSS. Generated by tools/build_pdp_css.py. */\n" + fix(B.asset_ref("\n".join(rules))) + "\n")
    print(out.name, len(rules), "rules", out.stat().st_size, "bytes")

# Home page. Theme-only additions are appended at the end.
rules = B.dedupe_keep_last([r for r in B.R["index.html"] if not B.PREVIEW_ONLY.match(r)])
extra = "/* theme additions */\n.vph video{position:absolute;inset:0;width:100%;height:100%;object-fit:cover}\n"
out = B.theme_assets / "embrae-sections.css"
out.write_text("/* index.html: complete page CSS. Generated by tools/build_pdp_css.py. */\n" + fix(B.asset_ref("\n".join(rules))) + "\n" + extra)
print(out.name, len(rules), "rules", out.stat().st_size, "bytes")

# Content pages (Phase 6): embrae-page-<name>.css, picked by template suffix / blog / article in theme.liquid.
CONTENT = ["the-embrae-system", "skin-quiz", "our-ingredients", ("faq", "faqs"), "our-story", "why-we-exist",
           "our-philosophy", "our-values", "a-note-from-the-founder", "journal",
           ("article", "how-to-patch-test-a-new-product")]  # all 12 articles share one identical rule list
for item in CONTENT:
    name, src = item if isinstance(item, tuple) else (item, item)
    rules = B.dedupe_keep_last([r for r in B.R[f"{src}.html"] if not B.PREVIEW_ONLY.match(r)])
    out = B.theme_assets / f"embrae-page-{name}.css"
    out.write_text(f"/* {src}.html: complete page CSS. Generated by tools/build_pdp_css.py. */\n" + fix(B.asset_ref("\n".join(rules))) + "\n")
    print(out.name, len(rules), "rules", out.stat().st_size, "bytes")
