#!/usr/bin/env python3
"""Create the `journal` blog and its 12 articles from the source article pages, and write snippets/journal-art.liquid.

Additive and re-runnable: the blog and the article metafield definitions are created if missing; articles are
created, or updated by handle (only articles in the journal blog are touched; the `news` blog is never read or changed).
Usage: python3 tools/setup_journal.py [--dry-run]
"""
import json, re
from datetime import datetime
from links import ARTICLE_PAGES, link, parse, root
from shop import DRY, check, gql

txt = lambda e: re.sub(r"\s+", " ", e.get_text(" ", strip=True)) if e else ""
ART = {}  # "<handle>-<context>" -> placeholder svg


def art(handle, ctx, svg):
    if svg is not None:
        ART.setdefault(f"{handle}-{ctx}", re.sub(r"\s+", " ", str(svg)))


def rel(a):
    return a["href"].removesuffix(".html")


# ---------- read the source ----------
articles = []
for h in sorted(ARTICLE_PAGES):
    html = (root / f"source/pages/{h}.html").read_text()
    s = parse(html)
    body = s.select_one("#ar-body")
    for a in body.select("a[href]"):
        a["href"] = link(a["href"])
    d, m = s.select_one(".ar-d b"), s.select_one(".ar-d i")
    seo = json.loads((root / f"source/seo/{h}.json").read_text())
    stage = re.search(r"stage:'(\w+)'", html)
    articles.append({
        "handle": h, "title": txt(s.select_one(".ar-h1")), "summary": txt(s.select_one(".ar-sub")),
        "date": datetime.strptime(f"{txt(d)} {txt(m)}", "%d %b %Y").strftime("%Y-%m-%dT09:00:00Z"),
        "read_time": txt([x for x in s.select(".ar-meta > span") if "read" in x.get_text()][0]),
        "body": body.decode_contents().strip(), "related": [rel(a) for a in s.select(".ar-rc")],
        "stage": stage.group(1) if stage else "", "seo": seo})
    art(h, "hero", s.select_one(".ar-img svg"))
    for a in s.select(".ar-rc"):
        art(rel(a), "related", a.select_one(".ar-ri svg"))

j = parse((root / "source/pages/journal.html").read_text())
for sel, ctx in ((".jr-lead", "lead"), (".jr-si", "thumb"), (".jr-card .jr-a", "card"), (".jr-pk", "pick")):
    for a in j.select(sel):
        art(rel(a), ctx, a.select_one("svg"))

(root / "embraecare/snippets/journal-art.liquid").write_text(
    "{% doc %}\n  Placeholder illustrations for journal articles, shown until an article image is set.\n"
    "  Generated by tools/setup_journal.py.\n\n  @param {string} key - <article handle>-<hero|related|lead|thumb|card|pick>\n{% enddoc %}\n"
    "{%- case key -%}\n" + "".join(f"  {{%- when '{k}' -%}}{v}\n" for k, v in ART.items()) + "{%- endcase -%}\n")
print(len(articles), "articles,", len(ART), "illustrations")

# ---------- store ----------
blog = next((b for b in gql('{ blogs(first:20){ nodes{ id handle } } }')["blogs"]["nodes"] if b["handle"] == "journal"), None)
if not blog:
    r = gql("""mutation($b: BlogCreateInput!){ blogCreate(blog:$b){ blog{ id handle } userErrors{ field message code } } }""",
            {"b": {"title": "The Journal", "handle": "journal", "templateSuffix": "journal", "commentPolicy": "CLOSED"}}, mutation=True)
    if not DRY: check(r["blogCreate"]); blog = r["blogCreate"]["blog"]; print("created blog journal")
    else: blog = {"id": "gid://dry/blog"}

have = {n["key"] for n in gql('{ metafieldDefinitions(first:50, ownerType:ARTICLE, namespace:"embrae"){ nodes{ key } } }')["metafieldDefinitions"]["nodes"]}
for key, name, typ, desc in [("read_time", "Read time", "single_line_text_field", "e.g. 3 min read"),
                             ("related", "Related articles", "list.single_line_text_field", "Article handles in the journal blog"),
                             ("stage", "Reader stage", "single_line_text_field", "Analytics label: unaware, problem, solution, brand or most")]:
    if key in have: continue
    r = gql("""mutation($d: MetafieldDefinitionInput!){ metafieldDefinitionCreate(definition:$d){ createdDefinition{ key } userErrors{ field message code } } }""",
            {"d": {"namespace": "embrae", "key": key, "name": name, "type": typ, "ownerType": "ARTICLE", "description": desc, "pin": True}}, mutation=True)
    if not DRY: check(r["metafieldDefinitionCreate"]); print("created article field", key)

existing = {} if DRY else {a["handle"]: a["id"] for a in gql(
    'query($id: ID!){ blog(id:$id){ articles(first:100){ nodes{ id handle } } } }', {"id": blog["id"]})["blog"]["articles"]["nodes"]}
for a in articles:
    fields = {"title": a["title"], "handle": a["handle"], "body": a["body"], "summary": a["summary"], "isPublished": True,
              "publishDate": a["date"], "author": {"name": "EMBRAE"}, "templateSuffix": "journal",
              "metafields": [
                  {"namespace": "embrae", "key": "read_time", "type": "single_line_text_field", "value": a["read_time"]},
                  {"namespace": "embrae", "key": "related", "type": "list.single_line_text_field", "value": json.dumps(a["related"])},
                  {"namespace": "embrae", "key": "stage", "type": "single_line_text_field", "value": a["stage"] or "-"},
                  {"namespace": "global", "key": "title_tag", "type": "single_line_text_field", "value": a["seo"]["title_tag"]},
                  {"namespace": "global", "key": "description_tag", "type": "multi_line_text_field", "value": a["seo"]["meta_description"]}]}
    if a["handle"] in existing:
        r = gql("""mutation($id: ID!, $a: ArticleUpdateInput!){ articleUpdate(id:$id, article:$a){ article{ handle } userErrors{ field message code } } }""",
                {"id": existing[a["handle"]], "a": fields}, mutation=True)
        if not DRY: check(r["articleUpdate"]); print("updated", a["handle"])
    else:
        r = gql("""mutation($a: ArticleCreateInput!){ articleCreate(article:$a){ article{ handle } userErrors{ field message code } } }""",
                {"a": {**fields, "blogId": blog["id"]}}, mutation=True)
        if not DRY: check(r["articleCreate"]); print("created", a["handle"])
